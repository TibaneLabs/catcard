//! Generates the register table and the linker script for the Precursor image.
//!
//! **Register table.** The stock gateware describes itself: every betrusted-soc build
//! emits a `csr.csv` listing each control register's address, and stores a copy inside
//! the bitstream image so tools can read it off a device. Hand-copying addresses out of
//! that file is how a firmware ends up writing to `d11ctime` when it meant `usbdev`, so
//! the table is generated from the file instead, for the release selected by feature.
//! Bit-level field layouts are not in the CSV; those are written by hand in `src/`, each
//! with its source.
//!
//! **Linker script.** Milestone 1 runs from external SRAM only: the image is written to
//! `0x4000_0000` over the USB debug bridge and entered there (`tools/precursor/run.py`).
//! Nothing here touches flash.

use std::env;
use std::fmt::Write as _;
use std::fs;
use std::path::PathBuf;

/// External SRAM, 16 MiB, cached.
/// Source: gateware csr.csv `memory_region,sram_ext,0x40000000,16777216` (both releases) [C]
const SRAM_BASE: u32 = 0x4000_0000;
const SRAM_LEN: u32 = 16 * 1024 * 1024;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("set by cargo"));
    let out = PathBuf::from(env::var("OUT_DIR").expect("set by cargo"));

    let gw = gateware_from_features();
    let csv_path = manifest.join("gateware").join(format!("csr-{gw}.csv"));
    println!("cargo:rerun-if-changed={}", csv_path.display());
    println!("cargo:rerun-if-changed=build.rs");
    let csv = fs::read_to_string(&csv_path)
        .unwrap_or_else(|e| panic!("reading {}: {e}", csv_path.display()));
    fs::write(out.join("csr.rs"), generate_table(gw, &csv)).expect("writing csr.rs");

    // Only the firmware target links against our script; host builds are a stub.
    if env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("riscv32") {
        fs::write(out.join("precursor.x"), linker_script()).expect("writing precursor.x");
        println!("cargo:rustc-link-search={}", out.display());
        // Emitted here rather than in .cargo/config.toml so RUSTFLAGS cannot drop it
        // (see the note at the top of .cargo/config.toml).
        println!("cargo:rustc-link-arg-bins=-Tprecursor.x");
    }
}

fn gateware_from_features() -> &'static str {
    let picked: Vec<&str> = [
        ("CARGO_FEATURE_GW_V0_9_5", "v0.9.5"),
        ("CARGO_FEATURE_GW_V0_9_14", "v0.9.14"),
    ]
    .iter()
    .filter(|(var, _)| env::var_os(var).is_some())
    .map(|&(_, gw)| gw)
    .collect();
    match picked.as_slice() {
        [one] => one,
        [] => panic!("select a gateware release: --features gw-v0_9_5 or gw-v0_9_14"),
        many => {
            panic!("select exactly one gateware release, got {many:?} (try --no-default-features)")
        }
    }
}

/// `csr_register,<name>,<addr>,<words>,<rw>` becomes `pub const <NAME>: usize`.
/// `csr_base`, `memory_region` and the git revision come along for the ride; the
/// `words` count is kept because multi-word registers (the 64-bit ticktimer) need it.
fn generate_table(gw: &str, csv: &str) -> String {
    let mut regs = String::new();
    let mut bases = String::new();
    let mut mems = String::new();
    let mut rev = None;
    for line in csv.lines().filter(|l| !l.starts_with('#')) {
        let f: Vec<&str> = line.split(',').collect();
        match f.as_slice() {
            ["csr_register", name, addr, words, ..] => {
                let n = name.to_ascii_uppercase();
                writeln!(regs, "    pub const {n}: usize = {addr};").unwrap();
                writeln!(regs, "    pub const {n}_WORDS: usize = {words};").unwrap();
            }
            ["csr_base", name, addr, ..] => {
                writeln!(
                    bases,
                    "    pub const {}: usize = {addr};",
                    name.to_ascii_uppercase()
                )
                .unwrap();
            }
            ["memory_region", name, addr, len, ..] => {
                let n = name.to_ascii_uppercase();
                writeln!(mems, "    pub const {n}: usize = {addr};").unwrap();
                writeln!(mems, "    pub const {n}_LEN: usize = {len};").unwrap();
            }
            ["git_rev", r, ..] => rev = Some(r.to_string()),
            _ => {}
        }
    }
    let rev = rev.expect("csr.csv carries a git_rev line");
    format!(
        "// Generated by catcard-precursor/build.rs from gateware/csr-{gw}.csv -- do not edit.\n\
         // Source: betrusted-soc {rev}, csr.csv as stored in the release's soc_csr.bin [C]\n\
         \n\
         /// The gateware release this table was generated from.\n\
         pub const GATEWARE_REV: &str = \"{rev}\";\n\
         \n\
         /// Individual control registers, by their csr.csv name.\n\
         #[allow(dead_code)]\n\
         pub mod reg {{\n{regs}}}\n\
         \n\
         /// Base address of each peripheral's register page.\n\
         #[allow(dead_code)]\n\
         pub mod base {{\n{bases}}}\n\
         \n\
         /// Memory-mapped regions (framebuffer, flash, SRAM, ...).\n\
         #[allow(dead_code)]\n\
         pub mod mem {{\n{mems}}}\n"
    )
}

fn linker_script() -> String {
    format!(
        "/* Generated by catcard-precursor/build.rs -- do not edit. */\n\
         OUTPUT_ARCH(riscv)\n\
         ENTRY(_start)\n\
         \n\
         MEMORY\n\
         {{\n\
         \x20 /* The whole external SRAM: Xous is not running, nothing else owns it. */\n\
         \x20 SRAM : ORIGIN = {SRAM_BASE:#X}, LENGTH = {SRAM_LEN:#X}\n\
         }}\n\
         \n\
         /* Stack at the top of SRAM, growing down towards .bss. */\n\
         _stack_top = ORIGIN(SRAM) + LENGTH(SRAM);\n\
         \n\
         SECTIONS\n\
         {{\n\
         \x20 /* _start must be the first byte: the runner enters at ORIGIN(SRAM). */\n\
         \x20 .text ORIGIN(SRAM) : {{\n\
         \x20   KEEP(*(.text.start))\n\
         \x20   *(.text.trap)\n\
         \x20   *(.text .text.*)\n\
         \x20 }} > SRAM\n\
         \x20 .rodata : ALIGN(4) {{ *(.srodata .srodata.*) *(.rodata .rodata.*) }} > SRAM\n\
         \x20 .data : ALIGN(4) {{\n\
         \x20   __global_pointer$ = . + 0x800;\n\
         \x20   *(.sdata .sdata.*) *(.data .data.*)\n\
         \x20 }} > SRAM\n\
         \x20 .bss (NOLOAD) : ALIGN(4) {{\n\
         \x20   _sbss = .;\n\
         \x20   *(.sbss .sbss.*) *(.bss .bss.*) *(COMMON)\n\
         \x20   . = ALIGN(4);\n\
         \x20   _ebss = .;\n\
         \x20 }} > SRAM\n\
         \x20 /DISCARD/ : {{ *(.eh_frame) *(.eh_frame_hdr) }}\n\
         }}\n"
    )
}
