/// What a reviewed line is about.
#[derive(Copy, Clone, PartialEq, Eq, Debug)]
pub enum Kind {
    /// Value leaving.
    Send,
    /// A token amount.
    Token,
    /// Authority handed to somebody else.
    Approve,
    /// A durable nonce being spent.
    Nonce,
    /// What the transaction will pay for priority.
    Budget,
    /// An account being opened.
    Account,
    /// Who pays the fee.
    Payer,
    /// A signature slot.
    Signer,
    /// Something this device could not read.
    Warning,
}

