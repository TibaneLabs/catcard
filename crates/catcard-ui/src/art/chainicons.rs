/// The colour and 1-bit marks for a ticker, if there are any.
pub fn mark(ticker: &str) -> Option<(&'static Indexed, &'static Bitmap)> {
    Some(match ticker {
        "BTC" => (&BTC, &BTC_MONO),
        "ETH" => (&ETH, &ETH_MONO),
        "SOL" => (&SOL, &SOL_MONO),
        "LTC" => (&LTC, &LTC_MONO),
        "BCH" => (&BCH, &BCH_MONO),
        "DOGE" => (&DOGE, &DOGE_MONO),
        "TRX" => (&TRX, &TRX_MONO),
        "MONA" => (&MONA, &MONA_MONO),
        "XEP" => (&XEP, &XEP_MONO),
        _ => return None,
    })
}
