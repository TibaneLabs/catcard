//! The CatCard cat, as 1-bit pixel art.
//!
//! Hand-drawn at this exact size, not rasterised from the logo SVG. At 48x38 every
//! pixel is a decision — vector geometry that small produces stems, gaps and
//! half-pixel taper that have to be argued with one at a time, and the result still
//! reads worse than something drawn as pixels.
//!
//! The source is `cat-48x38.png` beside this file, white-on-black: **lit pixels are
//! the ink**, the same polarity as the panel. It is a filled silhouette, so the eyes,
//! whiskers, nose and mouth are holes in it rather than strokes.
//!
//! To change the art, edit the PNG and re-emit this table from it.
//!
//! Row-major, most significant bit leftmost, 6 byte(s) per row.

