//! An 8x8 bitmap font, stored in SSD1306 column order.
//!
//! Source: <https://github.com/dhepper/font8x8> (`font8x8_basic.h`), public domain,
//! by Daniel Hepper, after Marcel Sondaar's original.
//!
//! The upstream table stores each glyph as eight **rows**, least-significant bit
//! leftmost. The SSD1306 addresses memory as **columns** of eight vertical pixels with
//! the least-significant bit at the top, so the glyphs are transposed here at
//! generation time. That makes drawing a character a straight copy of eight bytes into
//! the framebuffer instead of a per-pixel loop — which matters on an 80 MHz core
//! redrawing a screen.
//!
//! Generated file — do not hand-edit.

