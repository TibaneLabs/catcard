/// The glyph for `c`, or the glyph for `?` if it is outside the table.
///
/// Substituting rather than failing keeps rendering total: a stray byte in a label
/// shows as `?` instead of aborting a screen draw.
pub fn glyph(c: u8) -> &'static [u8; GLYPH_SIZE] {
    if (FIRST_CHAR..=LAST_CHAR).contains(&c) {
        &GLYPHS[(c - FIRST_CHAR) as usize]
    } else {
        &GLYPHS[(b'?' - FIRST_CHAR) as usize]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_covers_printable_ascii() {
        assert_eq!(GLYPHS.len(), 95);
        assert_eq!(FIRST_CHAR, b' ');
        assert_eq!(LAST_CHAR, b'~');
    }

    #[test]
    fn space_is_blank_and_nothing_else_is() {
        assert_eq!(*glyph(b' '), [0u8; GLYPH_SIZE]);
        for c in (FIRST_CHAR + 1)..=LAST_CHAR {
            assert_ne!(*glyph(c), [0u8; GLYPH_SIZE], "{:?} is blank", c as char);
        }
    }

    #[test]
    fn out_of_range_characters_fall_back_to_question_mark() {
        let q = *glyph(b'?');
        assert_eq!(*glyph(0x00), q);
        assert_eq!(*glyph(0x7F), q);
        assert_eq!(*glyph(0xFF), q);
    }

    #[test]
    fn glyphs_are_transposed_into_column_order() {
        // A capital I is a recognisable shape: its centre column carries most of the
        // ink, and the outer columns much less. In row order this would be inverted,
        // so this catches a missing transpose.
        let i = glyph(b'I');
        let centre = i[3].count_ones() + i[4].count_ones();
        let edges = i[0].count_ones() + i[7].count_ones();
        assert!(centre > edges, "I looks wrong in column order: {i:02x?}");
    }

    #[test]
    fn distinct_characters_have_distinct_glyphs() {
        // A generation bug that repeated one glyph would be invisible until someone
        // read a screen.
        let mut seen: Vec<[u8; GLYPH_SIZE]> = GLYPHS.to_vec();
        seen.sort_unstable();
        let before = seen.len();
        seen.dedup();
        // Some fonts legitimately share glyphs; allow a couple but not wholesale reuse.
        assert!(before - seen.len() <= 2, "too many duplicate glyphs");
    }
}
